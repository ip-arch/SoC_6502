#include "amap.h"


char dec[16] = {
 0x40, 0x79, 0x24, 0x30,
 0x19, 0x12, 0x02, 0x58,
 0x00, 0x18, 0x08, 0x03,
 0x27, 0x21, 0xff, 0x00};

char segDec(int in){
	if (in>0xF) {
		return dec[in & 0x0F];
	} else {
		return dec[in] | 0x80;
	}
}                               
